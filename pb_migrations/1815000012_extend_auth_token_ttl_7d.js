// Расширяет срок действия токена аутентификации для users с 24 часов (86400 сек)
// до 7 дней (604800 сек).
//
// Зачем: пользователи разлогинивались посреди работы — через 24 часа простоя
// токен истекал, первый же ответ 401 запускал pb.afterSend -> authStore.clear() ->
// user = null, из-за чего интерфейс деградировал: пропадала возможность менять
// столбцы таблицы (терялись несохранённые настройки колонок), а автор счёта
// отображался как "-".
//
// Влияет только на вновь выдаваемые токены; уже выданные сессии остаются
// действительными до истечения их исходного срока. Для активно работающих
// пользователей параллельно добавлен клиентский keepalive (authRefresh перед
// истечением), поэтому это миграция — страховка для случая простоя, а не
// замена активному обновлению сессии.
//
// Значение 7 дней, а не 30 (значение по умолчанию в PocketBase) — сознательный
// компромисс между удобством сессии и изначальным намерением решения,
// ограничившего срок 24 часами.
//
// `down` возвращает 86400 — то самое состояние, которое оставила миграция
// 1811000000_set_auth_token_ttl_24h.js, поэтому откат строго обратный.
migrate(
  (app) => {
    const collection = app.findCollectionByNameOrId('_pb_users_auth_');

    unmarshal(
      {
        authToken: {
          duration: 604800,
        },
      },
      collection,
    );

    return app.save(collection);
  },
  (app) => {
    const collection = app.findCollectionByNameOrId('_pb_users_auth_');

    unmarshal(
      {
        authToken: {
          duration: 86400,
        },
      },
      collection,
    );

    return app.save(collection);
  },
);
