import type { ThreadDirection } from './mail-thread-builder';

/**
 * Подписи линии переписки. Отдельный файл не ради порядка, а ради правила
 * fast-refresh: файл, который рисует письмо, экспортирует только компоненты,
 * а весь текст живёт здесь и им пользуются три поверхности — конструктор,
 * цепочка внутри формы и подсказки зон сброса.
 */

/** «Ответ на» вверх, «ответ» вниз: слова направления, а не стрелки. */
export const MAIL_CHAIN_DIRECTION_LABELS: Record<ThreadDirection, string> = {
  anchor: 'текущее письмо',
  up: 'ответ на',
  down: 'ответ',
};

/**
 * Подпись письма, с которого цепочка начинается.
 *
 * «Ответ на» такому письму не подходит по существу, а не по вкусу: отвечать
 * не на что, над ним в линии ничего нет, и шапка «ответ на / Исходящее» обещала
 * бы несуществующее письмо выше. Именно «цепочка», а не «переписка»: под ключом
 * без родителя в линии собираются все начала, их может быть несколько, и каждое
 * начинает свою цепочку, а не переписку целиком.
 */
export const MAIL_CHAIN_ROOT_LABEL = 'начало цепочки';

/**
 * Подпись шапки письма. Направление само по себе не различает начало цепочки и
 * её середину — оба шага вверх, — поэтому начало передаётся отдельным признаком, а
 * не угадывается по номеру строки: цепочек в линии может быть несколько, и
 * второе начало стоит в середине списка.
 *
 * Началом становится только шаг вверх. Открытое письмо остаётся текущим, даже
 * если отвечать ему не на что, — открытым его сделал человек, а не граф; а шаг
 * вниз принадлежит снятому с переписки письму, которое рисуется последним
 * корнем и в цепочку не входит.
 */
export function mailChainDirectionLabel(direction: ThreadDirection, startsChain: boolean): string {
  if (direction === 'up' && startsChain) return MAIL_CHAIN_ROOT_LABEL;
  return MAIL_CHAIN_DIRECTION_LABELS[direction];
}

/**
 * Заметки о том, почему ветка показана не вся. Живут здесь, а не по месту: в
 * конструкторе и в цепочке внутри формы речь об одном и том же ограничении, и
 * разные формулировки выдали бы два разных обещания.
 */
export const MAIL_CHAIN_TRUNCATION_NOTE = (maxDepth: number): string =>
  `Показана не вся ветка: письма глубже ${maxDepth} уровней и те, что встретились второй раз по другому пути, не разворачиваются`;

